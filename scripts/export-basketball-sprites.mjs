import sharp from 'sharp'
import { readFile, writeFile } from 'node:fs/promises'

const source = 'art-source/basketball/renders'
const assets = 'assets/basketball'
const timing = JSON.parse(process.argv[2])
const poses = JSON.parse(await readFile(source + '/poses.json'))
const spriteWidth = poses.spriteWidth
const size = poses.width
const courtScale = spriteWidth / size
const spriteXOffset = 270 * 282 / 512 - spriteWidth / 2
const spriteYOffset = (270 - spriteWidth) * 1.5
const frameWidth = 320
const frameHeight = 480
const columns = 6
const transparent = '#00000000'

async function pack(kind, frames) {
  const rows = Math.ceil(frames.length / columns)
  const layers = await Promise.all(frames.map(async (_, index) => ({
    input: await sharp(`${source}/${kind}-${index}.png`).resize(frameWidth, frameHeight).png().toBuffer(),
    left: (index % columns) * frameWidth,
    top: Math.floor(index / columns) * frameHeight,
  })))
  await sharp({ create: { width: columns * frameWidth, height: rows * frameHeight, channels: 4, background: transparent } })
    .composite(layers).webp({ quality: kind === 'walk' ? 80 : 86, alphaQuality: 100, effort: 6 }).toFile(`${assets}/player-${kind}-atlas.webp`)
  return rows
}

const shotRows = await pack('shot', timing.shot)
const walkRows = await pack('walk', timing.walk)
const setPose = poses.shot.findIndex(pose => pose.name === 'set')
const setIndex = timing.shot.indexOf(timing.keys[setPose])
await sharp(`${source}/shot-${setIndex}.png`)
  .webp({ quality: 80, alphaQuality: 100, effort: 6 }).toFile(assets + '/player-set.webp')

for (const [name, index] of [['ready', 0], ['rest', timing.shot.length - 1]]) {
  await sharp(`${source}/shot-${index}.png`).resize(1024, 1536).webp({ quality: 76, alphaQuality: 100, effort: 6 })
    .toFile(`${assets}/player-${name}.webp`)
}

const heldBallKeyframes = poses.shot.flatMap(({ ball }, index) => ball
  ? [[timing.keys[index], Number((ball[0] * courtScale + spriteXOffset).toFixed(2)), Number((ball[1] * courtScale + spriteYOffset).toFixed(2))]]
  : [])
const previewLayers = await Promise.all(timing.shot.map(async (_, index) => ({
  input: await sharp(`${source}/shot-${index}.png`).resize(320, 480).png().toBuffer(),
  left: index % 3 * 320,
  top: Math.floor(index / 3) * 480,
})))
await sharp({ create: { width: 960, height: 960, channels: 4, background: '#faf7f0' } })
  .composite(previewLayers).png().toFile('art-source/basketball-review/character-review.png')
await writeFile('src/basketball-character-frames.ts', `// Generated by scripts/build-basketball-animation.py.
export const spriteColumns = ${columns}
export const playerSpriteWidth = ${spriteWidth}
export const playerSpriteXOffset = ${spriteXOffset}
export const playerSpriteYOffset = ${spriteYOffset}
export const shotRows = ${shotRows}
export const walkRows = ${walkRows}
export const walkFrameCount = ${timing.walk.length}
export const shotTicks = ${JSON.stringify(timing.shot)}
export const shotReleaseTick = ${timing.keys[poses.shot.findIndex(pose => pose.name === 'release')]}
export const heldBallKeyframes = ${JSON.stringify(heldBallKeyframes)} as const
`)
