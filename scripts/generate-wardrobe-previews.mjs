import { readFile, writeFile, mkdir, readdir, unlink } from 'node:fs/promises'
import { createRequire } from 'node:module'
import vm from 'node:vm'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import ts from 'typescript'
import sharp from 'sharp'
import { createElement } from 'react'
import { renderToStaticMarkup } from 'react-dom/server'

const root = fileURLToPath(new URL('../', import.meta.url))
const directory = path.join(root, 'assets/bedtime/previews')
const source = await readFile(path.join(root, 'src/bedtime-outfits.tsx'), 'utf8')
const artwork = new Map()
for (const [, specifier] of source.matchAll(/from ['"]([^'"]+\.(?:webp|avif))['"]/g)) {
  const png = await sharp(path.resolve(root, 'src', specifier)).png().toBuffer()
  artwork.set(specifier, `data:image/png;base64,${png.toString('base64')}`)
}
const require = createRequire(import.meta.url)
const module = { exports: {} }
vm.runInNewContext(ts.transpileModule(source, {
  compilerOptions: { module: ts.ModuleKind.CommonJS, jsx: ts.JsxEmit.ReactJSX },
}).outputText, {
  module, exports: module.exports,
  require: specifier => artwork.has(specifier) ? { default: artwork.get(specifier) } : require(specifier),
})
const { bedtimeChoices, bedtimeOutfits, GarmentArt, SetArt } = module.exports
await mkdir(directory, { recursive: true })
const generated = new Set()
const imports = []
const previews = {}
let index = 0

async function generate(outfit, part, small = false) {
  const Component = part === 'sets' ? SetArt : GarmentArt
  const markup = renderToStaticMarkup(createElement(Component, { outfit, garment: part }))
    .replace('<svg ', '<svg xmlns="http://www.w3.org/2000/svg" ')
  const [, , width, height] = markup.match(/viewBox="([^"]+)"/)[1].split(' ').map(Number)
  const scale = Math.min((small ? 80 : 192) / width, (small ? 96 : 256) / height)
  const filename = `${small ? 'category' : outfit.id}-${part}.webp`
  await sharp(Buffer.from(markup)).resize(Math.round(width * scale), Math.round(height * scale))
    .webp({ quality: 85, alphaQuality: 100, effort: 6 }).toFile(path.join(directory, filename))
  generated.add(filename)
  const identifier = `preview${index++}`
  imports.push(`import ${identifier} from '../assets/bedtime/previews/${filename}'`)
  return identifier
}

for (const outfit of bedtimeChoices) {
  const parts = [...(bedtimeOutfits.includes(outfit) ? ['sets'] : []), ...outfit.parts]
  previews[outfit.id] = {}
  for (const part of parts) previews[outfit.id][part] = await generate(outfit, part)
}
const category = bedtimeOutfits.find(outfit => outfit.id === 'cherry-gingham')
const icons = {}
for (const part of ['sets', ...category.parts]) icons[part] = await generate(category, part, true)
const object = value => `{ ${Object.entries(value).map(([key, entry]) => `${JSON.stringify(key)}: ${typeof entry === 'string' ? entry : object(entry)}`).join(', ')} }`
await writeFile(path.join(root, 'src/wardrobe-previews.ts'),
  '// Generated by npm run generate:wardrobe-previews after artwork or fit changes.\n'
  + "import type { Garment } from './bedtime-outfits'\n" + imports.join('\n') + '\n\n'
  + "type PreviewPart = Garment | 'sets'\n"
  + `export const wardrobePreviews: Record<string, Partial<Record<PreviewPart, string>>> = ${object(previews)}\n`
  + `export const categoryPreviews: Record<PreviewPart, string> = ${object(icons)}\n`)
for (const filename of await readdir(directory)) {
  if (!generated.has(filename) && filename.endsWith('.webp')) await unlink(path.join(directory, filename))
}
console.log(`Generated ${generated.size} previews from the approved artwork and fitting bounds.`)
